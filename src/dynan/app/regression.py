"""Automatic regression-test generation.

PDF section 3.3 requires minimised, confirmed inputs to be added automatically
to the project's regression suite so later pipeline runs exercise them, and
the generated test must reveal the error on the base version while checking
its absence - plus correct behaviour - on the patched version.

Where the suite lives matters. dynAn writes into a **project-owned**
directory (``tests.regression_suite``), never into the target's repository:
mutating the code under validation would corrupt the very thing being
measured, and would make the next run's diff meaningless.

The emitted file is an ordinary dynAn test manifest. There is no special
"generated test" execution path - the next run loads it exactly like a
hand-written suite, which is what makes the promotion loop real rather than
decorative.
"""

from __future__ import annotations

import os
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from ..domain.enums import BuildProfile, InputDelivery, Version
from ..domain.models import (
    BuildResult,
    Finding,
    GeneratedRegressionTest,
    TestCaseSpec,
)
from ..infra.runner import ExecutionRequest, TargetRunner
from . import signature as signature_mod

MANIFEST_NAME = "manifest.yaml"
INPUTS_DIR = "inputs"

_HEADER_COMMENT = """\
# dynAn generated regression suite
#
# Every entry here was produced automatically from a confirmed, reproduced and
# minimised failure. Add this file to `tests.manifests` in your dynAn
# configuration so future validations execute it.
#
# Generated entries are safety checks: they assert the recorded failure no
# longer occurs. They intentionally do not assert functional output, so they
# are never used as the independent oracle for a functional-regression claim.
#
# This file is rewritten by dynAn. Hand-written tests belong in their own
# manifest.
"""


def _safe_id(value: str) -> str:
    cleaned = "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in value)
    return cleaned[:64].strip("_") or "generated"


class RegressionSuiteWriter:
    """Accumulates generated tests and persists them as a manifest."""

    def __init__(self, suite_dir: Path, *, run_id: str) -> None:
        self.suite_dir = Path(suite_dir)
        self.run_id = run_id
        self.manifest_path = self.suite_dir / MANIFEST_NAME
        self._entries: dict[str, dict[str, Any]] = {}
        self._generated: list[GeneratedRegressionTest] = []

    # -- existing suite --------------------------------------------------

    def load_existing(self) -> None:
        """Read any previously generated entries so they are preserved."""
        if not self.manifest_path.is_file():
            return
        try:
            doc = yaml.safe_load(self.manifest_path.read_text("utf-8")) or {}
        except (OSError, yaml.YAMLError):
            return
        for entry in doc.get("tests") or []:
            if isinstance(entry, dict) and entry.get("id"):
                self._entries[str(entry["id"])] = entry

    # -- emitting --------------------------------------------------------

    def emit(
        self,
        finding: Finding,
        test: TestCaseSpec,
        input_bytes: bytes,
        *,
        minimized: bool,
    ) -> GeneratedRegressionTest:
        """Write one generated test's input and register its manifest entry."""
        test_id = _safe_id(f"regress_{finding.signature.digest}_{test.test_id}")
        inputs_dir = self.suite_dir / INPUTS_DIR
        inputs_dir.mkdir(parents=True, exist_ok=True)

        input_name = f"{INPUTS_DIR}/{test_id}.bin"
        (self.suite_dir / input_name).write_bytes(input_bytes)

        # ARGV inputs cannot be delivered from a file, so the generated test
        # keeps the original delivery mechanism and inlines the payload.
        delivery = test.delivery
        entry: dict[str, Any] = {
            "id": test_id,
            "category": "security",
            "description": (
                f"Regression test generated by dynAn from finding "
                f"{finding.finding_id} ({finding.signature.describe()})"
            ),
            "delivery": delivery.value,
            "generated": True,
            "expect_baseline_signature": finding.signature.describe(),
            "expect": {
                "must_not_crash": True,
                "provenance": (
                    f"dynAn run {self.run_id}; minimised reproducer for "
                    f"{finding.signature.describe()}"
                ),
            },
        }
        if delivery == InputDelivery.ARGV:
            entry["input"] = input_bytes.decode("utf-8", errors="replace")
        else:
            entry["input_file"] = input_name
        if test.argv:
            entry["argv"] = list(test.argv)
        if test.timeout_s:
            entry["timeout_s"] = test.timeout_s

        self._entries[test_id] = entry

        generated = GeneratedRegressionTest(
            test_id=test_id,
            finding_id=finding.finding_id,
            input_artifact=input_name,
            manifest_path=str(self.manifest_path),
            delivery=delivery,
            argv=list(test.argv),
            expected_base_signature=finding.signature.describe(),
            notes=(
                "minimised input" if minimized else "original input (not minimised)"
            ),
        )
        self._generated.append(generated)
        return generated

    # -- persistence -----------------------------------------------------

    def flush(self) -> list[GeneratedRegressionTest]:
        """Write the manifest atomically and return the generated tests."""
        if not self._entries:
            return self._generated

        self.suite_dir.mkdir(parents=True, exist_ok=True)
        document = {
            "version": 1,
            "oracle": {
                "provenance": (
                    "dynAn generated suite - entries assert the absence of a "
                    "previously confirmed failure"
                )
            },
            "defaults": {"delivery": InputDelivery.STDIN.value},
            "tests": [self._entries[key] for key in sorted(self._entries)],
        }
        body = _HEADER_COMMENT + yaml.safe_dump(
            document, sort_keys=False, allow_unicode=True, default_flow_style=False
        )

        fd, tmp = tempfile.mkstemp(dir=str(self.suite_dir), prefix=".manifest-", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                handle.write(body)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp, self.manifest_path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

        return self._generated


def verify_generated_test(
    generated: GeneratedRegressionTest,
    finding: Finding,
    test: TestCaseSpec,
    input_bytes: bytes,
    *,
    runner: TargetRunner,
    base_build: BuildResult,
    patched_build: BuildResult,
    source_roots: list[Path],
) -> GeneratedRegressionTest:
    """Execute a generated test on both versions and record what happened.

    The PDF asks the generated test to reveal the error on the base version
    and show its absence on the patched one. We verify both halves by actually
    running them rather than asserting the intent.
    """
    probe = TestCaseSpec(
        test_id=generated.test_id,
        category=test.category,
        description="verification of generated regression test",
        delivery=test.delivery,
        argv=list(test.argv),
        timeout_s=test.timeout_s,
        expectation=test.expectation,
        generated=True,
    )

    base_exec = runner.execute(
        ExecutionRequest(
            test=probe,
            build=base_build,
            input_bytes=input_bytes,
            execution_id=f"verify.{Version.BASE.value}.{generated.test_id}",
        )
    )
    patched_exec = runner.execute(
        ExecutionRequest(
            test=probe,
            build=patched_build,
            input_bytes=input_bytes,
            execution_id=f"verify.{Version.PATCHED.value}.{generated.test_id}",
        )
    )

    base_obs = signature_mod.observe(
        base_exec, probe, finding.signature, source_roots=source_roots
    )
    patched_obs = signature_mod.observe(
        patched_exec, probe, finding.signature, source_roots=source_roots
    )

    generated.verified_fails_on_base = base_obs.matched
    generated.verified_passes_on_patched = not patched_obs.matched

    notes = [generated.notes] if generated.notes else []
    notes.append(
        f"base: {base_obs.detail}" if not base_obs.matched else "base: reproduces the failure"
    )
    notes.append(
        "patched: failure absent"
        if not patched_obs.matched
        else f"patched: STILL reproduces ({patched_obs.detail})"
    )
    generated.notes = "; ".join(notes)
    return generated


def suite_summary(generated: list[GeneratedRegressionTest]) -> str:
    if not generated:
        return "no regression tests generated"
    verified = sum(
        1
        for g in generated
        if g.verified_fails_on_base and g.verified_passes_on_patched
    )
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    return f"{len(generated)} generated, {verified} verified on both versions ({stamp})"
