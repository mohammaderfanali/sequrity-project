"""Reproducer bundles and replay stability.

PDF section 3.3 requires, for every confirmed finding: the triggering input,
the exact program revision, build settings, effective environment variables
and the full execution command, stored so the failure can be re-run - plus at
least three replays with unstable cases identified.

The bundle is written to be useful without dynAn: ``reproduce.sh`` is a plain
shell script a reviewer can run directly against the recorded binary.

A finding that does not reproduce on every attempt is marked unstable, and the
decision engine then refuses to let the run be reported as complete. That is
deliberate - an intermittent failure is exactly the "unstable finding" the
specification names as a reason for exit code 40.
"""

from __future__ import annotations

import json
import shlex
from pathlib import Path

from ..config.schema import AnalysisConfig
from ..domain.models import (
    BuildResult,
    Finding,
    ReplayAttempt,
    ReproductionResult,
    SourceRevision,
    TestCaseSpec,
)
from ..infra.runner import ExecutionRequest, TargetRunner, describe_command, env_exports
from ..infra.store import RunStore
from . import signature as signature_mod

_SCRIPT_TEMPLATE = """#!/bin/sh
# Reproducer generated by dynAn for finding {finding_id}
#
#   error      : {error}
#   revision   : {revision}
#   binary     : {binary}
#   sha256     : {sha256}
#   profile    : {profile}
#
# The binary path below refers to the build produced during the original run.
# Rebuild the recorded revision with the same profile if it is no longer present.

set -eu
cd "$(dirname "$0")"

{exports}

{invocation}
status=$?
echo "dynAn: exited with status ${{status}}" >&2
exit ${{status}}
"""


class ReproductionService:
    """Builds reproducer bundles and measures replay stability."""

    def __init__(
        self,
        *,
        runner: TargetRunner,
        store: RunStore,
        run_id: str,
        analysis: AnalysisConfig,
        source_roots: list[Path],
    ) -> None:
        self.runner = runner
        self.store = store
        self.run_id = run_id
        self.analysis = analysis
        self.source_roots = source_roots

    def reproduce(
        self,
        finding: Finding,
        test: TestCaseSpec,
        build: BuildResult,
        input_bytes: bytes,
        revision: SourceRevision,
    ) -> ReproductionResult:
        """Replay a finding and write its bundle."""
        attempts: list[ReplayAttempt] = []
        target = finding.signature
        bundle_rel = f"reproducers/{_safe(finding.finding_id)}"

        last_execution = None
        for attempt_no in range(1, max(self.analysis.replay_count, 3) + 1):
            execution = self.runner.execute(
                ExecutionRequest(
                    test=test,
                    build=build,
                    input_bytes=input_bytes,
                    execution_id=f"{finding.execution_id}.replay{attempt_no}",
                )
            )
            last_execution = execution
            observation = signature_mod.observe(
                execution, test, target, source_roots=self.source_roots
            )
            attempts.append(
                ReplayAttempt(
                    attempt=attempt_no,
                    execution_id=execution.execution_id,
                    reproduced=observation.matched,
                    observed_signature=(
                        observation.signature.describe() if observation.signature else None
                    ),
                )
            )

        reproduced = sum(1 for a in attempts if a.reproduced)
        total = len(attempts)

        result = ReproductionResult(
            finding_id=finding.finding_id,
            bundle_path=bundle_rel,
            attempts=attempts,
            reproduced_count=reproduced,
            total_attempts=total,
            # "Stable" means every replay reproduced it. Anything less is an
            # unstable finding, which must not be reported as settled.
            stable=reproduced == total and total >= 3,
            revision=_revision_label(revision),
            binary_sha256=build.binary_sha256,
            argv=list(last_execution.argv) if last_execution else [],
            env=dict(last_execution.env) if last_execution else {},
            delivery=test.delivery,
            build_profile=build.profile,
        )

        self._write_bundle(result, finding, test, build, input_bytes, revision, last_execution)
        return result

    # -- bundle ---------------------------------------------------------

    def _write_bundle(
        self,
        result: ReproductionResult,
        finding: Finding,
        test: TestCaseSpec,
        build: BuildResult,
        input_bytes: bytes,
        revision: SourceRevision,
        execution,
    ) -> None:
        base = result.bundle_path
        self.store.write_artifact(self.run_id, f"{base}/input.bin", input_bytes)

        metadata = {
            "finding_id": finding.finding_id,
            "error": finding.signature.describe(),
            "error_type": finding.signature.error_type.value,
            "detection_mechanism": finding.signature.detection.value,
            "source_location": {
                "file": finding.signature.file,
                "line": finding.signature.line,
                "function": finding.signature.function,
            },
            "test_id": test.test_id,
            "version": finding.version.value,
            "build_profile": build.profile.value,
            "revision": {
                "kind": revision.kind,
                "commit": revision.commit,
                "content_hash": revision.content_hash,
                "origin": revision.origin,
                "dirty": revision.dirty,
                "exact_vcs_revision": revision.is_exact_vcs_revision,
            },
            "binary": {
                "path": build.binary_path,
                "sha256": build.binary_sha256,
            },
            "build": {
                "toolchain": build.toolchain,
                "compiler_flags": build.compiler_flags,
                "commands": [c.argv for c in build.commands],
            },
            "execution": {
                "argv": result.argv,
                "delivery": test.delivery.value,
                "cwd": execution.cwd if execution else None,
                "timeout_s": execution.timeout_s if execution else None,
                "environment": result.env,
                "sandbox": execution.sandbox if execution else None,
            },
            "replays": {
                "attempts": result.total_attempts,
                "reproduced": result.reproduced_count,
                "stable": result.stable,
                "detail": [
                    {
                        "attempt": a.attempt,
                        "reproduced": a.reproduced,
                        "observed": a.observed_signature,
                        "execution_id": a.execution_id,
                    }
                    for a in result.attempts
                ],
            },
        }
        self.store.write_artifact(
            self.run_id, f"{base}/metadata.json", json.dumps(metadata, indent=2)
        )

        if execution is not None:
            script = _SCRIPT_TEMPLATE.format(
                finding_id=finding.finding_id,
                error=finding.signature.describe(),
                revision=_revision_label(revision),
                binary=build.binary_path or "<unknown>",
                sha256=build.binary_sha256 or "<unknown>",
                profile=build.profile.value,
                exports=env_exports(execution) or "# (no environment overrides)",
                invocation=_invocation(execution),
            )
            path = self.store.resolve_artifact(self.run_id, f"{base}/reproduce.sh")
            self.store.write_artifact(self.run_id, f"{base}/reproduce.sh", script)
            path.chmod(0o755)


def _invocation(execution) -> str:
    from ..domain.enums import InputDelivery

    rendered = " ".join(shlex.quote(part) for part in execution.argv)
    if execution.delivery == InputDelivery.STDIN:
        return f"{rendered} < input.bin"
    return rendered


def _revision_label(revision: SourceRevision) -> str:
    if revision.commit:
        return f"commit {revision.commit}" + (" (dirty worktree)" if revision.dirty else "")
    return f"content-hash {revision.content_hash} (not a VCS revision)"


def _safe(value: str) -> str:
    return "".join(ch if ch.isalnum() or ch in "._-" else "_" for ch in value)


def describe_bundle(result: ReproductionResult) -> str:
    return (
        f"{result.reproduced_count}/{result.total_attempts} replays reproduced "
        f"({'stable' if result.stable else 'UNSTABLE'})"
    )
