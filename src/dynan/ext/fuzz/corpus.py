"""Input generation.

Chooses between grammar expansion and corpus mutation, and builds the
synthetic test case that describes how a generated input is delivered.

The two strategies are complementary: the grammar explores the shapes the
format's author anticipated, mutation explores what happens just outside them.
Under ``strategy: both`` the generator favours the grammar, because a
structurally valid input that reaches deep parsing code is worth more than a
mangled one the first validity check rejects.
"""

from __future__ import annotations

import random

from ...config.schema import FuzzConfig
from ...domain.enums import InputDelivery, TestCategory, Version
from ...domain.models import OracleExpectation, TestCaseSpec
from .grammar import Grammar
from .mutator import mutate, splice

#: Probability of choosing the grammar when both strategies are available.
_GRAMMAR_BIAS = 0.6


def build_probe(version: Version, delivery: InputDelivery) -> TestCaseSpec:
    """Synthetic test case describing how fuzz inputs reach the target.

    Reuses the configured delivery mechanism so the fuzzer exercises the
    binary exactly as the real suite does. Its expectation is only
    ``must_not_crash``: a fuzzer has no oracle for correct output, so it must
    never be treated as one - which also keeps it out of functional-regression
    reasoning.
    """
    return TestCaseSpec(
        test_id=f"fuzz_{version.value}",
        category=TestCategory.SECURITY,
        description="generated by the fuzzing extension",
        delivery=delivery,
        expectation=OracleExpectation(
            must_not_crash=True,
            provenance="fuzzer (not an independent correctness oracle)",
        ),
        generated=True,
    )


def generate(
    config: FuzzConfig,
    grammar: Grammar | None,
    corpus: list[bytes],
    rng: random.Random,
) -> bytes:
    """Produce one candidate input."""
    use_grammar = grammar is not None and (
        config.strategy == "grammar"
        or (config.strategy == "both" and rng.random() < _GRAMMAR_BIAS)
    )
    if use_grammar:
        assert grammar is not None
        return grammar.generate(rng, max_bytes=config.max_input_bytes)

    if not corpus:
        if grammar is not None:
            return grammar.generate(rng, max_bytes=config.max_input_bytes)
        # No grammar and no seeds: fall back to random bytes. This mostly
        # exercises the rejection path, which is why the doctor nudges towards
        # supplying a grammar.
        return bytes(rng.randrange(256) for _ in range(rng.randint(1, 64)))

    seed = rng.choice(corpus)
    if len(corpus) > 1 and rng.random() < 0.2:
        seed = splice(seed, rng.choice(corpus), rng, max_bytes=config.max_input_bytes)
    return mutate(seed, rng, max_bytes=config.max_input_bytes)


def seed_corpus(inputs: dict[str, bytes]) -> list[bytes]:
    """Non-empty test inputs, de-duplicated, usable as mutation seeds."""
    seen: set[bytes] = set()
    corpus: list[bytes] = []
    for data in inputs.values():
        if data and data not in seen:
            seen.add(data)
            corpus.append(data)
    return corpus
