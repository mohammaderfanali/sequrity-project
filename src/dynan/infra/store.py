"""Filesystem-backed run persistence.

A completed run must stay inspectable without re-executing anything, so the
store holds both the structured result and the raw evidence it references.
Large payloads (process output, crash reports, inputs, binaries) live as
artifacts; ``results.json`` references them by run-relative path.

No database: the access pattern is "write once, read by id, list recent", which
the filesystem serves directly. Introducing one would add an operational
dependency without removing any work.

Guarantees:

* Writes to ``results.json``/``manifest.json`` are atomic (temp file + rename),
  so a crashed run never leaves a half-written report.
* Artifact paths are validated against the run root, so a malformed run id or
  artifact reference cannot read outside the store.
* Completed runs are treated as immutable; nothing overwrites a previous run.
"""

from __future__ import annotations

import json
import os
import re
import tempfile
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterator

from ..domain.models import ProgressEvent, RunSummary, ValidationRun

#: Run ids are generated by dynAn, but they also arrive from HTTP routes and
#: CLI arguments, so they are validated on every lookup.
_RUN_ID_RE = re.compile(r"^[0-9]{8}T[0-9]{6}Z-[0-9a-f]{8}$")

_RESULTS = "results.json"
_MANIFEST = "manifest.json"
_EVENTS = "events.jsonl"


class StoreError(RuntimeError):
    """Persistence failed, or a requested run/artifact is not addressable."""


def generate_run_id(now: datetime | None = None) -> str:
    """Time-ordered, collision-resistant run identifier.

    The timestamp prefix makes directory listings sort chronologically; the
    random suffix keeps two runs started in the same second distinct.
    """
    stamp = (now or datetime.now(timezone.utc)).strftime("%Y%m%dT%H%M%SZ")
    return f"{stamp}-{os.urandom(4).hex()}"


def is_valid_run_id(run_id: str) -> bool:
    return bool(_RUN_ID_RE.match(run_id))


@dataclass(slots=True)
class RunPaths:
    """Resolved locations for one run's data."""

    root: Path

    @property
    def results(self) -> Path:
        return self.root / _RESULTS

    @property
    def manifest(self) -> Path:
        return self.root / _MANIFEST

    @property
    def events(self) -> Path:
        return self.root / _EVENTS

    @property
    def logs(self) -> Path:
        return self.root / "logs"

    @property
    def evidence(self) -> Path:
        return self.root / "evidence"

    @property
    def reproducers(self) -> Path:
        return self.root / "reproducers"

    @property
    def sources(self) -> Path:
        return self.root / "sources"

    @property
    def diff(self) -> Path:
        return self.root / "diff.patch"

    def ensure(self) -> None:
        for path in (self.root, self.logs, self.evidence, self.reproducers, self.sources):
            path.mkdir(parents=True, exist_ok=True)


def _atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-", suffix=".part")
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


class RunStore:
    """Reads and writes validation runs under an artifacts root."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).expanduser().resolve()
        self.runs_dir = self.root / "runs"
        self.cache_dir = self.root / "cache"

    # -- layout ---------------------------------------------------------

    def ensure(self) -> None:
        try:
            self.runs_dir.mkdir(parents=True, exist_ok=True)
            self.cache_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise StoreError(f"cannot create artifacts root {self.root}: {exc}") from exc

    def paths(self, run_id: str) -> RunPaths:
        if not is_valid_run_id(run_id):
            raise StoreError(f"invalid run id: {run_id!r}")
        return RunPaths(self.runs_dir / run_id)

    def create(self, run_id: str) -> RunPaths:
        paths = self.paths(run_id)
        if paths.root.exists():
            raise StoreError(f"run {run_id} already exists; runs are never overwritten")
        paths.ensure()
        return paths

    def exists(self, run_id: str) -> bool:
        return is_valid_run_id(run_id) and self.paths(run_id).results.exists()

    # -- artifacts ------------------------------------------------------

    def resolve_artifact(self, run_id: str, relative: str) -> Path:
        """Resolve a run-relative artifact path, refusing escapes.

        The web API exposes artifact downloads, so this check is a security
        boundary rather than a tidiness measure.
        """
        paths = self.paths(run_id)
        root = paths.root.resolve()
        candidate = (root / relative).resolve()
        try:
            candidate.relative_to(root)
        except ValueError as exc:
            raise StoreError(
                f"artifact path escapes run directory: {relative!r}"
            ) from exc
        return candidate

    def write_artifact(self, run_id: str, relative: str, data: bytes | str) -> str:
        """Store an artifact and return the run-relative path to reference it."""
        target = self.resolve_artifact(run_id, relative)
        payload = data.encode("utf-8") if isinstance(data, str) else data
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            target.write_bytes(payload)
        except OSError as exc:
            raise StoreError(f"cannot write artifact {relative}: {exc}") from exc
        return relative

    def read_artifact(self, run_id: str, relative: str) -> bytes:
        target = self.resolve_artifact(run_id, relative)
        if not target.is_file():
            raise StoreError(f"artifact not found: {relative}")
        return target.read_bytes()

    # -- events ---------------------------------------------------------

    def append_event(self, run_id: str, event: ProgressEvent) -> None:
        """Append one progress event.

        JSON Lines: appendable without rewriting, and tailable by the web UI
        while the run is still in flight.
        """
        paths = self.paths(run_id)
        paths.root.mkdir(parents=True, exist_ok=True)
        line = event.model_dump_json() + "\n"
        try:
            with paths.events.open("a", encoding="utf-8") as handle:
                handle.write(line)
                handle.flush()
        except OSError as exc:
            raise StoreError(f"cannot append event for run {run_id}: {exc}") from exc

    def read_events(self, run_id: str, *, after: int = -1) -> list[ProgressEvent]:
        paths = self.paths(run_id)
        if not paths.events.exists():
            return []
        events: list[ProgressEvent] = []
        with paths.events.open("r", encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line:
                    continue
                try:
                    event = ProgressEvent.model_validate_json(line)
                except ValueError:
                    continue  # tolerate a torn final line while a run is live
                if event.sequence > after:
                    events.append(event)
        return events

    # -- runs -----------------------------------------------------------

    def save(self, run: ValidationRun) -> None:
        """Persist the full run plus its listing projection, atomically."""
        paths = self.paths(run.run_id)
        paths.ensure()
        _atomic_write(paths.results, run.model_dump_json(indent=2).encode("utf-8"))
        _atomic_write(
            paths.manifest, run.to_summary().model_dump_json(indent=2).encode("utf-8")
        )

    def load(self, run_id: str) -> ValidationRun:
        paths = self.paths(run_id)
        if not paths.results.is_file():
            raise StoreError(f"run not found: {run_id}")
        try:
            return ValidationRun.model_validate_json(paths.results.read_text("utf-8"))
        except (OSError, ValueError) as exc:
            raise StoreError(f"cannot read run {run_id}: {exc}") from exc

    def load_summary(self, run_id: str) -> RunSummary:
        """Read the lightweight projection, falling back to the full record."""
        paths = self.paths(run_id)
        if paths.manifest.is_file():
            try:
                return RunSummary.model_validate_json(paths.manifest.read_text("utf-8"))
            except (OSError, ValueError):
                pass
        return self.load(run_id).to_summary()

    def iter_run_ids(self) -> Iterator[str]:
        if not self.runs_dir.is_dir():
            return
        for entry in sorted(self.runs_dir.iterdir(), reverse=True):
            if entry.is_dir() and is_valid_run_id(entry.name):
                yield entry.name

    def list_summaries(self, *, limit: int | None = None) -> list[RunSummary]:
        """Newest-first run listing, skipping runs too damaged to summarise."""
        summaries: list[RunSummary] = []
        for run_id in self.iter_run_ids():
            try:
                summaries.append(self.load_summary(run_id))
            except StoreError:
                continue
            if limit is not None and len(summaries) >= limit:
                break
        return summaries

    def latest_run_id(self) -> str | None:
        return next(self.iter_run_ids(), None)

    def write_json(self, run_id: str, relative: str, payload: object) -> str:
        return self.write_artifact(
            run_id, relative, json.dumps(payload, indent=2, default=str)
        )
